export default async function (page) {
  const at = (label) => console.log(`${((Date.now() - globalThis.T0) / 1000).toFixed(2)}s ${label}`)
  const tap = async (sel, fx = 0.5, fy = 0.5) => {
    const b = await page.locator(sel).first().boundingBox()
    at(sel)
    await page.mouse.click(b.x + b.width * fx, b.y + b.height * fy)
  }
  const wait = (ms) => page.waitForTimeout(ms)
  await tap('[data-knob]')
  await wait(1500)
  await tap('.porch-art .mat')
  await wait(2500)
  await tap('[data-vent]')
  await wait(2500)
  await tap('[data-vent]')
  await wait(2200)
  await tap('[data-vent]')
  await wait(3500)
  await tap('.porch-art .plant')
  await wait(800)
  await tap('.porch-art .plant')
  await wait(1200)
  await tap('.porch-art .lamp')
  await wait(3000)
  await tap('.porch-art .flowers')
  await wait(1500)
  await tap('.porch-art .flowers')
  await wait(1500)
  await tap('.leaf-art .plate')
  await wait(1500)
  await tap('[data-knock]', 0.2, 0.9)
  await wait(1500)
  for (let i = 0; i < 3; i++) {
    await tap('.dw__sky .moon')
    await wait(500)
  }
  await wait(1500)
  at('end')
}
