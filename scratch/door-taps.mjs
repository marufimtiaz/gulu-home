export default async function (page, out) {
  const tap = async (sel, fx = 0.5, fy = 0.5) => {
    const b = await page.locator(sel).first().boundingBox()
    await page.mouse.click(b.x + b.width * fx, b.y + b.height * fy)
  }
  const snap = (n) => page.screenshot({ path: `scratch/${out}-${n}.png` })
  await tap('.porch-art .mat')
  await page.waitForTimeout(350)
  await snap('mat')
  await page.waitForTimeout(1600)
  await tap('[data-knob]')
  await page.waitForTimeout(250)
  await snap('knob')
  await page.waitForTimeout(800)
  await tap('[data-vent]')
  await tap('[data-vent]')
  await page.waitForTimeout(500)
  await snap('vent')
  await tap('.porch-art .lamp')
  await tap('.porch-art .lamp')
  await tap('.porch-art .lamp')
  await page.waitForTimeout(1600)
  await snap('lamp')
  await tap('.porch-art .flowers', 0.5, 0.3)
  await page.waitForTimeout(500)
  await snap('flowers')
  await tap('.leaf-art .plate')
  await tap('.leaf-art .plate')
  await page.waitForTimeout(800)
  await snap('plate')
  for (let i = 0; i < 3; i++) await tap('.who')
  await page.waitForTimeout(700)
  await snap('who')
}
