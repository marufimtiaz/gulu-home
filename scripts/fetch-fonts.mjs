#!/usr/bin/env node
// Downloads every font the site uses into public/fonts/ and writes src/styles/fonts.css
// with local @font-face rules (latin + bengali subsets only). Re-run to refresh.
//   node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const outDir = resolve(root, 'public/fonts')
const FAMILIES = [
  // the house (site two's identity)
  'Fraunces:ital,opsz,wght,SOFT,WONK@0,9..144,400..900,0..100,0..1;1,9..144,400..900,0..100,0..1',
  'Caveat:wght@500;700',
  'DM+Sans:wght@400;500;700',
  'Hind+Siliguri:wght@400;500;700',
  'Atma:wght@500;700',
  // the reception card
  'Galada', // Bangla calligraphic display
  'Tiro+Bangla:ital@0;1', // formal Bangla serif
  'Noto+Serif+Bengali:wght@400;600',
  'Pinyon+Script', // English script for the names
  'Cinzel:wght@500;700', // engraved capitals
  'Cormorant+Garamond:ital,wght@0,400;0,600;1,400', // formal English body
]
const KEEP = new Set(['latin', 'latin-ext', 'bengali'])
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

await mkdir(outDir, { recursive: true })
let css = '/* generated by scripts/fetch-fonts.mjs — do not edit */\n'
let count = 0
for (const fam of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${fam}&display=swap`
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`${fam}: HTTP ${res.status}`)
  const text = await res.text()
  // blocks look like:  /* bengali */ @font-face { ... src: url(...) format('woff2'); unicode-range: ...; }
  const blocks = [...text.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)]
  for (const [, subset, block] of blocks) {
    if (!KEEP.has(subset)) continue
    const src = block.match(/url\((https:[^)]+\.woff2)\)/)[1]
    const family = block.match(/font-family:\s*'([^']+)'/)[1]
    const style = block.match(/font-style:\s*(\w+)/)[1]
    const weight = block.match(/font-weight:\s*([\d ]+)/)[1].trim().replace(' ', '-')
    const file = `${family.replace(/\s+/g, '')}-${style}-${weight}-${subset}.woff2`
    const buf = Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer())
    await writeFile(resolve(outDir, file), buf)
    css += `/* ${subset} */\n` + block.replace(src, `/fonts/${file}`) + '\n'
    count++
  }
}
await writeFile(resolve(root, 'src/styles/fonts.css'), css)
console.log(`${count} font files → public/fonts/, src/styles/fonts.css written`)
